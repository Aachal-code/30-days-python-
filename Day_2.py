country = 'Nepal'
city = 'Kathmandu'
age = 89
not_married = True
skills = ['HTML', 'CSS', 'JS', 'React', 'Python']
person_info = {
    'firstname': 'Aachal',
    'lastname': 'Bhandari',
    'country': 'Nepal',
    'city': 'Kathmandu'
}

